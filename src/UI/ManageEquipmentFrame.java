    private void setupTable()
    {
        tableModel = new DefaultTableModel(
            new Object[][]{},
            new String[]{"Equipment ID", "Name", "Category", "Status", "Location"}
        )
        {
            @Override
            public boolean isCellEditable(int row, int column)
            {
                return false;
            }
        };

        tblEquipment.setModel(tableModel);
        tblEquipment.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tblEquipment.getTableHeader().setReorderingAllowed(false);
    }
    
    private void loadEquipmentTable()
    {
        tableModel.setRowCount(0);

        List<Equipment> list = equipmentService.getAllEquipment();
        for (Equipment e : list)
        {
            tableModel.addRow(new Object[]
            {
                e.getEquipmentId(),
                e.getName(),
                e.getCategory(),
                e.getStatus(),
                e.getLocation()
            });
        }
    }


