    private void btnAddActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_btnAddActionPerformed
    {//GEN-HEADEREND:event_btnAddActionPerformed
        String id = txtEquipmentId.getText().trim();
        String name = txtName.getText().trim();
        String category = ( String ) cmbCategory.getSelectedItem();
        String status = ( String ) cmbStatus.getSelectedItem();
        String location = txtLocation.getText().trim();
        
        if ( id.isEmpty() || name.isEmpty())
        {
            lblMessage.setText("ID and Name are required.");
            return;
        }
        
        Equipment newEquipment = new Equipment( id, name, category, status, location );
        
        boolean added = equipmentService.addEquipment( newEquipment );
        
        if ( added )
        {
            lblMessage.setText("Equipment added Successfully.");
            loadEquipmentTable();
        }
        else
        {
            lblMessage.setText("Equipment ID already exists.");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_btnRemoveActionPerformed
    {//GEN-HEADEREND:event_btnRemoveActionPerformed
        int row = tblEquipment.getSelectedRow();
        
        if (row == -1)
        {
            lblMessage.setText("Please select equipment to remove.");
            return;
        }

        String equipmentId = (String) tableModel.getValueAt(row, 0);

        boolean removed = equipmentService.removeEquipment(equipmentId);

        if (removed)
        {
            lblMessage.setText("Equipment removed.");
            loadEquipmentTable();
        }
        else
        {
            lblMessage.setText("Cannot remove checked out equipment.");
        }
    }//GEN-LAST:event_btnRemoveActionPerformed

   
    

